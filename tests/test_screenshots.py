"""AGENT_UPDATE_7.md task 5: the screenshots folder is regenerated from the
packaged exe after every build, and this test makes forgetting impossible.

Skipped (with the reason) where the folder does not exist, so a fresh
checkout is not blocked; on a build machine the assertion is live.
"""

from __future__ import annotations

import re
import time
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SHOTS = ROOT / "screenshots"

REQUIRED = (
    "760x600_idle.png", "760x600_video.png", "760x600_running.png",
    "760x600_finished.png", "760x600_error.png",
    "900x700_idle.png", "900x700_video.png", "900x700_running.png",
    "900x700_finished.png", "900x700_error.png",
    "1100x800_idle.png", "1100x800_video.png", "1100x800_running.png",
    "1100x800_finished.png", "1100x800_error.png",
    "dialog_error.png", "dialog_first_run.png", "dialog_settings.png",
)


def newest_shot_dir() -> Path:
    dirs = [d for d in SHOTS.iterdir() if d.is_dir()] if SHOTS.is_dir() else []
    if not dirs:
        pytest.skip("no screenshots folder in this checkout (generated by the build)")
    return max(dirs, key=lambda d: d.stat().st_mtime)


def test_only_one_screenshot_folder() -> None:
    dirs = [d for d in SHOTS.iterdir() if d.is_dir()] if SHOTS.is_dir() else []
    if not dirs:
        # Fresh checkout: the set is regenerated by the build's post-build
        # step (AGU7 task 5) and asserted there.
        pytest.skip("no screenshots folder in this checkout (generated by the build)")
    assert len(dirs) == 1, f"older screenshot folders still present: {dirs}"


def test_required_pngs_exist_and_are_newer_than_the_stamp() -> None:
    shot_dir = newest_shot_dir()
    missing = [n for n in REQUIRED if not (shot_dir / n).is_file()]
    assert missing == [], f"missing required PNGs: {missing}"
    index_text = (shot_dir / "INDEX.txt").read_text(encoding="utf-8")
    match = re.search(r"built \(UTC\):\s+(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})", index_text)
    assert match is not None, "INDEX.txt lacks the build timestamp line"
    built = time.mktime(time.strptime(match.group(1), "%Y-%m-%d %H:%M:%S")) - time.timezone
    for name in REQUIRED:
        mtime = (shot_dir / name).stat().st_mtime
        assert mtime >= built, f"{name} is older than the build timestamp (a stale image)"


def test_index_lists_the_current_build_id() -> None:
    shot_dir = newest_shot_dir()
    index_text = (shot_dir / "INDEX.txt").read_text(encoding="utf-8")
    build_ids = re.findall(r"build id:\s*(\S.*)", index_text)
    assert build_ids, "INDEX.txt lacks a build id line"
    # cross-check with dist/DubTool/BUILD_INFO.txt when it exists (built here)
    info = ROOT / "dist" / "DubTool" / "BUILD_INFO.txt"
    if info.is_file():
        for line in info.read_text(encoding="utf-8").splitlines():
            if line.lstrip("\ufeff").startswith("build id:"):
                assert build_ids[0].strip() == line.split(":", 1)[1].strip(), (
                    "INDEX build id does not match the exe's BUILD_INFO.txt"
                )
                break
